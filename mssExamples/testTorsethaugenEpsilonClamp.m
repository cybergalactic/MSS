    fprintf('Check 2 PASS: %d cases inside [Tl, Tu] are bit-identical to the reference\n', size(HsTp,1));
else
    nFail = nFail + 1;
    fprintf('Check 2 FAIL: %d of %d cases inside [Tl, Tu] changed\n', nBad, size(HsTp,1));
end

