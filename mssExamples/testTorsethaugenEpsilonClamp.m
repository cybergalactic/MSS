    S = torsetSpectrum(HsTp(k,1), 2*pi/HsTp(k,2), W);
    if ~isequal(S(:).', Sref{k})
        nBad = nBad + 1;
        fprintf('  Hs = %g m, Tp = %g s differs from reference\n', HsTp(k,1), HsTp(k,2));
    end
