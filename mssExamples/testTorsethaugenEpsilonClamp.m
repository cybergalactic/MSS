if isequal(Sw(:).', SrefWind)
    fprintf('Check 3 PASS: wind sea at Tp = 3 s (below Tl) matches the clamped reference\n');
else
    nFail = nFail + 1;
    fprintf('Check 3 FAIL: wind sea at Tp = 3 s (below Tl) does not match the clamped reference\n');
end

if nFail > 0
    error('testTorsethaugenEpsilonClamp: %d check(s) failed.', nFail);
end
